import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { z } from "zod";

const surfaces = ["Runtime", "Registry", "UsageLedger", "UsageRequests", "DrainControl", "DrainPhase", "ReleaseTypes"] as const;
const identifier = z.string().regex(/^[A-Za-z_$][\w$]*$/u);
const declarationSchema = z.strictObject({
  from: z.string().regex(/^[a-zA-Z][a-zA-Z0-9-]*$/u),
  surfaces: z.array(z.enum(surfaces)).nonempty(),
  values: z.array(identifier).nonempty().optional(),
  types: z.array(identifier).nonempty().optional()
});

export const generateAdapterLegacyExports = (root: URL, names: string[]): void => {
  const declarations = names.flatMap((name) => {
    const declarationUrl = new URL(`${name}/legacyExports.json`, root);
    if (!existsSync(declarationUrl)) return [];
    return z.array(declarationSchema).parse(JSON.parse(readFileSync(declarationUrl, "utf8"))).map((item) => ({ ...item, name }));
  });

  for (const surface of surfaces) {
    const exports = declarations.filter((item) => item.surfaces.includes(surface))
      .flatMap(({ from, name, types, values }) => {
        const source = `from "./${name}/${from}.js";`;
        if (!types && !values) return [`export * ${source}`];
        return [
          ...(values ? [`export { ${values.join(", ")} } ${source}`] : []),
          ...(types ? [`export type { ${types.join(", ")} } ${source}`] : [])
        ];
      });
    const code = exports.length ? exports.join("\n") : "export {};";
    writeFileSync(new URL(`legacy${surface}.generated.ts`, root),
      `// Generated by scripts/generate-builtin-adapters.ts.\n${code}\n`);
  }
};
