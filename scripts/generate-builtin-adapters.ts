import { existsSync, readdirSync, writeFileSync } from "node:fs";

const root = new URL("../src/runtime/", import.meta.url);
const names = readdirSync(root, { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && existsSync(new URL(`${entry.name}/registration.ts`, root)))
  .map((entry) => entry.name).sort();
for (const name of names) {
  if (!/^[a-z][a-z0-9-]*$/u.test(name)) throw new Error(`Invalid bundled adapter directory: ${name}`);
}
const imports = names.map((name, index) => `import * as adapter${index} from "./${name}/registration.js";`);
const items = names.map((_, index) => `adapter${index}`).join(", ");
writeFileSync(new URL("builtinAdapters.generated.ts", root),
  `// Generated by scripts/generate-builtin-adapters.ts.\nimport type { RuntimeAdapter } from "./types.js";\n${imports.join("\n")}\n\nexport const builtinRuntimeRegistrations: readonly { adapter: RuntimeAdapter; defaultScaffoldRuntime?: boolean }[] = [${items}];\n`);
